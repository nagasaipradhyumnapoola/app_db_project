-- Student Database Management System - Supabase PostgreSQL Schema
-- ==============================================================================

-- 1. Create the public.students table
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    register_no TEXT NOT NULL,
    name TEXT NOT NULL,
    department TEXT NOT NULL,
    year INTEGER NOT NULL CHECK (year >= 1 AND year <= 4),
    email TEXT NOT NULL,
    teacher_id UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),

    -- Prevent duplicate register numbers for the same teacher
    CONSTRAINT students_teacher_register_no_unique UNIQUE (teacher_id, register_no)
);

-- 2. Indexes for fast query and search performance
CREATE INDEX IF NOT EXISTS idx_students_teacher_id 
    ON public.students (teacher_id);

CREATE INDEX IF NOT EXISTS idx_students_teacher_register_no 
    ON public.students (teacher_id, register_no);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;

-- 4. RLS Policies (Per-teacher Isolation)

-- Allow authenticated teachers to SELECT only their own student records
DROP POLICY IF EXISTS "Teachers can view their own students" ON public.students;
CREATE POLICY "Teachers can view their own students"
    ON public.students
    FOR SELECT
    TO authenticated
    USING (auth.uid() = teacher_id);

-- Allow authenticated teachers to INSERT their own student records
-- Enforces that teacher_id must match the authenticated user's ID
DROP POLICY IF EXISTS "Teachers can insert their own students" ON public.students;
CREATE POLICY "Teachers can insert their own students"
    ON public.students
    FOR INSERT
    TO authenticated
    WITH CHECK (auth.uid() = teacher_id);

-- Allow authenticated teachers to UPDATE only their own student records
DROP POLICY IF EXISTS "Teachers can update their own students" ON public.students;
CREATE POLICY "Teachers can update their own students"
    ON public.students
    FOR UPDATE
    TO authenticated
    USING (auth.uid() = teacher_id)
    WITH CHECK (auth.uid() = teacher_id);

-- Allow authenticated teachers to DELETE only their own student records
DROP POLICY IF EXISTS "Teachers can delete their own students" ON public.students;
CREATE POLICY "Teachers can delete their own students"
    ON public.students
    FOR DELETE
    TO authenticated
    USING (auth.uid() = teacher_id);

-- 5. Grant table access to authenticated users
GRANT SELECT, INSERT, UPDATE, DELETE ON public.students TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.students_id_seq TO authenticated;

